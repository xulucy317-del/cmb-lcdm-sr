"""Streaming access to the sharded spectra layout, distilled to what the
encoder pass needs: the *test split only*, normalised with the stats stored in
the run's ``scaler.npz`` (no training-statistics recomputation).

Expected on-disk layout (generated by the parent project on HPC):

    <dataset_dir>/
        theta.npy           (500_000, 6)  LHS-sampled cosmological parameters
        splits_v1.npz       split_id in {0,1,2}  (400k train / 50k val / 50k test)
    <shard_dir per channel>/
        spectra_00000.npz ... spectra_00099.npz
        each: spectra (5000, L_ch) float32, plus theta/ell (unused here)

Preprocessing applied per item: ``log10(spec / ref)`` (CPU), then per-ell
``(x - mu) / sigma`` on-device via :class:`NormWrapper` — identical to the
training-time pipeline, so encoder posteriors match the stored runs.
"""
from __future__ import annotations

import glob
import os
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import torch
from torch.utils.data import DataLoader, Dataset

_EPS = 1e-30


class ShardedSpectraDataset(Dataset):
    """Streams preprocessed CMB spectra from sharded .npz files.

    Parameters
    ----------
    shard_dirs : dict[channel_name, directory]
        e.g. ``{"tt": ".../shards_global_lhs"}`` for TT-only, or
        ``{"tt": ..., "ee": ".../shards_global_lhs_ee_lowl"}`` for TT+EE.
        Insertion order defines the channel order and must match training.
    refs : dict[channel_name, np.ndarray]
        Reference spectrum per channel (1D, length L_ch).
    indices : np.ndarray | None
        Subset of global row indices (e.g. the test split). If None -> all.
    expected_n : int | None
        Optional sanity check on total dataset size (500000 by default).
    n_shards : int
        Number of shards expected per channel (default 100).
    return_dict : bool
        If True, __getitem__ yields {ch: (L_ch,)} dicts (dual-encoder path);
        otherwise a stacked (C, L) tensor (same-length channels only).
    """

    def __init__(
        self,
        shard_dirs: Dict[str, str | Path],
        refs: Dict[str, np.ndarray],
        indices: Optional[np.ndarray] = None,
        expected_n: int | None = 500_000,
        n_shards: int = 100,
        return_dict: bool = False,
    ):
        super().__init__()
        self.channels = list(shard_dirs.keys())
        self.refs = {c: np.asarray(refs[c], dtype=np.float32) for c in self.channels}

        # Resolve shard paths per channel.
        self._paths: Dict[str, List[str]] = {}
        for ch, d in shard_dirs.items():
            all_paths = sorted(glob.glob(os.path.join(str(d), "spectra_*.npz")))
            paths = all_paths[:n_shards]
            assert len(paths) == n_shards, (
                f"channel '{ch}': expected {n_shards} shards in {d}, found {len(all_paths)}"
            )
            self._paths[ch] = paths

        # Build the global (shard, row) index using the first channel.
        ref_ch = self.channels[0]
        index: List[Tuple[int, int]] = []
        for shard_id, path in enumerate(self._paths[ref_ch]):
            n = int(np.load(path, allow_pickle=False)["spectra"].shape[0])
            for row in range(n):
                index.append((shard_id, row))
        if expected_n is not None:
            assert len(index) == expected_n, (
                f"Expected {expected_n} samples across {n_shards} shards, got {len(index)}"
            )

        self._global_index = index
        self._index: List[Tuple[int, int]] = (
            [index[i] for i in indices] if indices is not None else index
        )
        self._return_dict = return_dict

        # Per-channel memory-mapped spectra caches.
        self._cache: Dict[str, Dict[int, np.ndarray]] = {ch: {} for ch in self.channels}

    def _spectra(self, channel: str, shard_id: int) -> np.ndarray:
        cache = self._cache[channel]
        if shard_id not in cache:
            cache[shard_id] = np.load(self._paths[channel][shard_id], mmap_mode="r")["spectra"]
        return cache[shard_id]

    def __len__(self) -> int:
        return len(self._index)

    def __getitem__(self, idx: int):
        shard_id, row = self._index[idx]
        if self._return_dict:
            result: Dict[str, torch.Tensor] = {}
            for ch in self.channels:
                spec = self._spectra(ch, shard_id)[row].astype(np.float32)
                ratio = np.clip(spec / (self.refs[ch] + _EPS), _EPS, None)
                result[ch] = torch.from_numpy(np.log10(ratio))
            return result
        # Stacked path — requires same-length channels.
        L = self.refs[self.channels[0]].shape[0]
        out = np.empty((len(self.channels), L), dtype=np.float32)
        for c, ch in enumerate(self.channels):
            spec = self._spectra(ch, shard_id)[row].astype(np.float32)
            ratio = np.clip(spec / (self.refs[ch] + _EPS), _EPS, None)
            out[c] = np.log10(ratio)
        return torch.from_numpy(out)


class NormWrapper:
    """Wraps a DataLoader; applies (x - mu) / sigma on-device per batch.

    Stacked path: mu/sigma broadcast over the (C, L) feature shape.
    Dict path (dual-encoder): pass ``per_channel_stats={ch: (mu, sigma)}``.
    """

    def __init__(self, loader: DataLoader, mu, sigma, device: torch.device,
                 per_channel_stats: Optional[Dict[str, Tuple[np.ndarray, np.ndarray]]] = None):
        self.loader = loader
        self.device = device
        if mu is not None:
            mu_t = torch.from_numpy(np.asarray(mu, dtype=np.float32))
            sd_t = torch.from_numpy(np.asarray(sigma, dtype=np.float32))
            if mu_t.ndim == 1:
                mu_t = mu_t.unsqueeze(0)   # (1, L) -> broadcasts over C
                sd_t = sd_t.unsqueeze(0)
            self.mu    = mu_t.to(device)
            self.sigma = sd_t.to(device)
        else:
            self.mu = self.sigma = None
        if per_channel_stats is not None:
            self._ch_mu = {
                ch: torch.from_numpy(np.asarray(m, dtype=np.float32)).to(device)
                for ch, (m, _) in per_channel_stats.items()
            }
            self._ch_sigma = {
                ch: torch.from_numpy(np.asarray(s, dtype=np.float32)).to(device)
                for ch, (_, s) in per_channel_stats.items()
            }
        else:
            self._ch_mu = self._ch_sigma = None

    def __iter__(self):
        for batch in self.loader:
            if isinstance(batch, dict):
                yield {
                    ch: (batch[ch].to(self.device, non_blocking=True) - self._ch_mu[ch])
                        / self._ch_sigma[ch]
                    for ch in batch
                }
            else:
                x = batch.to(self.device, non_blocking=True)
                yield (x - self.mu) / self.sigma

    def __len__(self) -> int:
        return len(self.loader)


def build_test_loader(
    shard_dirs: Dict[str, str],
    scaler,
    splits_path: str | Path,
    batch_size: int = 1024,
    num_workers: int = 0,
    device: torch.device | None = None,
    n_shards: int = 100,
    expected_n: int = 500_000,
    force_dict_mode: bool = False,
) -> NormWrapper:
    """Test-split loader normalised with a run's stored :class:`ShardedScaler`.

    ``shard_dirs`` must cover every channel in ``scaler.channels``; the
    scaler's channel order (the training order) is authoritative. Channels
    with different lengths automatically use the per-channel dict path that
    :class:`~cmb_lcdm_sr.model.DualEncoderCVAE` expects.
    """
    device = device or torch.device("cpu")
    channels = scaler.channels
    missing = [ch for ch in channels if ch not in shard_dirs]
    if missing:
        raise ValueError(f"shard_dirs missing channels {missing}; scaler has {channels}")
    ordered_dirs = {ch: str(shard_dirs[ch]) for ch in channels}
    refs = {ch: scaler.refs[ch].astype(np.float32) for ch in channels}

    lengths = {ch: refs[ch].shape[0] for ch in channels}
    dict_mode = len(set(lengths.values())) > 1 or force_dict_mode

    split_id = np.load(Path(splits_path))["split_id"]
    idx_test = np.where(split_id == 2)[0]

    ds = ShardedSpectraDataset(
        shard_dirs=ordered_dirs, refs=refs, indices=idx_test,
        expected_n=expected_n, n_shards=n_shards, return_dict=dict_mode,
    )
    loader = DataLoader(
        ds, batch_size=batch_size, shuffle=False,
        num_workers=num_workers, pin_memory=(device.type == "cuda"),
        persistent_workers=(num_workers > 0),
        prefetch_factor=4 if num_workers > 0 else None,
    )
    if dict_mode:
        per_channel_stats = {ch: scaler.channel_stats(ch) for ch in channels}
        return NormWrapper(loader, None, None, device, per_channel_stats=per_channel_stats)
    return NormWrapper(loader, scaler.mu, scaler.sigma, device)
